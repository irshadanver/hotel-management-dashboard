type LocaleLabels = typeof labels.en;

interface LocaleContextValue {
  locale: Locale;
  direction: "ltr" | "rtl";
  isRTL: boolean;
  setLocale: (locale: Locale) => void;
  toggleLocale: () => void;
  tr: (text: string | number | undefined | null) => string;
  t: LocaleLabels;
}

const LocaleContext = createContext<LocaleContextValue | null>(null);

function getInitialLocale(): Locale {
  if (typeof window === "undefined") return "en";
  return window.localStorage.getItem(STORAGE_KEY) === "ar" ? "ar" : "en";
}

export function LocaleProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(getInitialLocale);

  const setLocale = (nextLocale: Locale) => {
    setLocaleState(nextLocale);
    window.localStorage.setItem(STORAGE_KEY, nextLocale);
  };

  const value = useMemo<LocaleContextValue>(() => {
    const direction = locale === "ar" ? "rtl" : "ltr";
    const tr = (text: string | number | undefined | null) => {
      if (text === undefined || text === null) return "";
      const normalized = String(text);
      if (locale !== "ar") return normalized;

      return arabicText[normalized] ?? translateDynamicText(normalized);
    };

    return {
      locale,
      direction,
      isRTL: direction === "rtl",
      setLocale,
      toggleLocale: () => setLocale(locale === "ar" ? "en" : "ar"),
      tr,
      t: labels[locale],
    };
  }, [locale]);

  useEffect(() => {
    document.documentElement.lang = locale;
    document.documentElement.dir = value.direction;
    document.documentElement.dataset.locale = locale;
  }, [locale, value.direction]);

  return (
    <LocaleContext.Provider value={value}>{children}</LocaleContext.Provider>
  );
}

export function useLocale() {
  const context = useContext(LocaleContext);
  if (!context) {
    throw new Error("useLocale must be used within LocaleProvider");
  }

  return context;
}
