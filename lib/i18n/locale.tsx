function translateDynamicText(text: string) {
  return text
    .replace(/\bGuests served\b/g, "نزلاء تم تقديم الخدمة لهم")
    .replace(/\bPer cover\b/g, "لكل غطاء")
    .replace(/\bof sales\b/g, "من المبيعات")
    .replace(/\bRoom nights booked\b/g, "ليالي غرف محجوزة")
    .replace(/\bdays ago\b/g, "أيام مضت")
    .replace(/\bToday\b/g, arabicText.Today)
    .replace(/\bYesterday\b/g, arabicText.Yesterday)
    .replace(/\bTomorrow\b/g, arabicText.Tomorrow)
    .replace(/\bSelected date\b/g, arabicText["Selected date"])
    .replace(/\bconfirmed\b/g, arabicText.confirmed)
    .replace(/\btrend average\b/g, arabicText["trend average"])
    .replace(/\bchecked in\b/g, arabicText["checked in"])
    .replace(/\bchecked out\b/g, arabicText["checked out"])
    .replace(/\bguests\b/gi, arabicText.Guests)
    .replace(/\brooms\b/gi, arabicText.rooms)
    .replace(/\bstandard\b/gi, arabicText.standard)
    .replace(/\bdeluxe\b/gi, arabicText.deluxe)
    .replace(/\bsuite\b/gi, arabicText.suite)
    .replace(/\bexecutive\b/gi, arabicText.executive)
    .replace(/\bof\b/g, "من")
    .replace(/\btransactions\b/g, "معاملات");
}

